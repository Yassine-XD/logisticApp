export function t(path, vars) {
  const val = path.split(".").reduce((o, k) => (o == null ? o : o[k]), es);
  if (val == null) return path;
  if (!vars) return val;
  return val.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? vars[k] : `{${k}}`));
}
